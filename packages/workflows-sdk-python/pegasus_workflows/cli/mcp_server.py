def tool_scaffold_workflow(name: str, dest: str) -> dict[str, Any]:
    """Scaffold a new workflow project at ``dest/name``.

    Wraps :func:`pegasus_workflows.cli.init.render_project`.

    Returns:
        ``{"ok": True, "project_dir": str, "files": [relative_path, ...]}``
        on success, or ``{"ok": False, "error": str}`` on failure.
    """
    dest_path = Path(dest).resolve()
    try:
        project_dir = render_project(name, dest_path)
    except (ValueError, FileExistsError, OSError) as exc:
        return {"ok": False, "error": str(exc)}

    files = sorted(
        str(p.relative_to(project_dir))
        for p in project_dir.rglob("*")
        if p.is_file()
    )
    return {"ok": True, "project_dir": str(project_dir), "files": files}


def tool_validate_manifest(path_or_toml: str) -> dict[str, Any]:
    """Validate a manifest file path or raw TOML text.

    Wraps :func:`pegasus_workflows.manifest.load_manifest`.  If *path_or_toml*
    resolves to an existing file, it is parsed directly.  Otherwise the value
    is treated as TOML text and written to a temporary file for parsing.

    Returns:
        ``{"ok": True, "manifests": [...]}`` on success, or
        ``{"ok": False, "error": str}`` on validation failure.
    """
    p = Path(path_or_toml)
    if p.is_file():
        try:
            manifests = load_manifest(p)
        except ManifestError as exc:
            return {"ok": False, "error": str(exc)}
        return {"ok": True, "manifests": [_manifest_to_dict(m) for m in manifests]}

    # Treat as raw TOML text.
    tmp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", suffix=".toml", encoding="utf-8", delete=False
        ) as tmp:
            tmp_path = Path(tmp.name)  # assign before write so finally can always unlink
            tmp.write(path_or_toml)
        try:
            manifests = load_manifest(tmp_path)
        except ManifestError as exc:
            return {"ok": False, "error": str(exc)}
    except OSError as exc:
        # NamedTemporaryFile creation or write failed — return structured error.
        return {"ok": False, "error": f"could not create temporary file: {exc}"}
    finally:
        if tmp_path is not None:
            tmp_path.unlink(missing_ok=True)

    return {"ok": True, "manifests": [_manifest_to_dict(m) for m in manifests]}


def _manifest_to_dict(m: Manifest) -> dict[str, Any]:
    return {
        "name": m.name,
        "version": m.version,
        "entry_points": list(m.entry_points),
        "source_dir": m.source_dir,
        "description": m.description,
        "required_actions": list(m.required_actions),
        "timeout_seconds": m.timeout_seconds,
    }


def tool_diagram_prompt(project_dir: str, workflow: str | None = None) -> dict[str, Any]:
    """Build the bring-your-own-agent diagram prompt(s) for a project's workflows.

    Returns the same prompt the ``pegasus-workflows diagram`` CLI prints — each
    workflow's Python source plus the exact ``<source_dir>/workflow.mmd`` output
    path and Mermaid formatting rules — so the calling agent draws the
    ``flowchart TD`` itself and writes it to that path. A ``workflow.mmd`` is
    required to package/publish. Read-only: gathers source and returns text, no
    network and no write. Pass *workflow* to scope to a single workflow name.

    Returns:
        ``{"ok": True, "prompts": [{"workflow", "out_path", "exists", "prompt"}, ...]}``
        on success, or ``{"ok": False, "error": str}`` on failure.
    """
    proj = Path(project_dir).resolve()
    try:
        manifests = load_manifest(proj)
    except ManifestError as exc:
        return {"ok": False, "error": str(exc)}

    if workflow is not None:
        manifests = [m for m in manifests if m.name == workflow]
        if not manifests:
            return {"ok": False, "error": f"no workflow named {workflow!r} in this project"}

    prompts: list[dict[str, Any]] = []
    for m in manifests:
        source_dir = proj / m.source_dir
        if not source_dir.is_dir():
            return {
                "ok": False,
                "error": f"workflow {m.name}: source_dir '{m.source_dir}' not found",
            }
        out_path = f"{m.source_dir}/{DIAGRAM_FILENAME}"
        prompts.append(
            {
                "workflow": m.name,
                "out_path": out_path,
                "exists": (source_dir / DIAGRAM_FILENAME).is_file(),
                "prompt": build_diagram_prompt(m.name, out_path, gather_source(source_dir)),
            }
        )
    return {"ok": True, "prompts": prompts}


def tool_package_project(project_dir: str) -> dict[str, Any]:
    """Package every workflow declared in ``project_dir`` into ``dist/``.

    Wraps :func:`pegasus_workflows.cli.package.package_project`.

    Returns:
        ``{"ok": True, "artifacts": [{name, version, zip_path, size_bytes}, ...]}``
        on success, or ``{"ok": False, "error": str}`` on failure.
    """
    try:
        results = _pkg_project(Path(project_dir).resolve())
    except (ManifestError, OSError) as exc:
        # The missing-diagram failure names a shell command (`pegasus-workflows
        # diagram`) that an MCP-only agent can't run. Rewrite the remedy to the
        # in-MCP path so scaffold → (draw) → package stays reachable without a
        # shell. See the `diagram_prompt` tool + pegasus://reference/manifest.
        message = str(exc)
        if DIAGRAM_FILENAME in message:
            return {
                "ok": False,
                "error": message,
                "remedy": (
                    f"A workflow diagram ({DIAGRAM_FILENAME}) is required to package. "
                    "Call the `diagram_prompt` tool to get each workflow's source and "
                    "output path, draw the Mermaid `flowchart TD` yourself, write it to "
                    "the path the tool names, then call `package_project` again."
                ),
            }
        return {"ok": False, "error": message}

    artifacts = [
        {
            "name": manifest.name,
            "version": manifest.version,
            "zip_path": str(zip_path),
            "size_bytes": zip_path.stat().st_size,
        }
        for manifest, zip_path in results
    ]
    return {"ok": True, "artifacts": artifacts}


def tool_validate_integration_config(
    integration_id: str,
    mapping: Any,
    rules: Any,
    corpus: Any,
    base_url: str,
    token: str,
    floor: str | None = None,
    inbound: Any | None = None,
) -> dict[str, Any]:
    """Dry-run the integration config publish gate. No write.

    Constructs a :class:`~pegasus_workflows.api.PegasusClient` from *base_url*
    and *token*, then calls
    :meth:`~pegasus_workflows.api.PegasusClient.validate_integration_config`.
    Pass *floor* for a new id with no built-in overlay, and *inbound* to gate the
    ingress ack/validation block too.

    Returns:
        ``{"ok": True, "report": {...}}`` on success, or
        ``{"ok": False, "error": str}`` on failure.
    """
    client = PegasusClient(base_url=base_url, token=token)
    try:
        report = client.validate_integration_config(
            integration_id,
            mapping=mapping,
            rules=rules,
            corpus=corpus,
            floor=floor,
            inbound=inbound,
        )
        return {"ok": True, "report": report}
    except Exception as exc:  # broad catch: httpx, PegasusApiError, network errors
        return {"ok": False, "error": str(exc)}


def tool_list_deployments(project_dir: str) -> dict[str, Any]:
    """Read a project's ``deployments.toml`` ledger. Read-only — no network, no write.

    Wraps :func:`pegasus_workflows.deployments.read_deployments`, so an agent can
    answer "where is this deployed / what's its id in env X" without scraping
    terminal output.

    Returns:
        ``{"ok": True, "deployments": {...}}`` (empty dict when no ledger exists),
        or ``{"ok": False, "error": str}`` on a malformed file.
    """
    try:
        deployments = read_deployments(Path(project_dir).resolve())
    except (OSError, ValueError) as exc:
        return {"ok": False, "error": str(exc)}
    return {"ok": True, "deployments": deployments}


def tool_list_profiles() -> dict[str, Any]:
    """List credential profile names + api_root. **Never** returns ``api_key``.

    Wraps :func:`pegasus_workflows.credentials.list_profile_summaries`. Secrets
    must not cross the MCP boundary, so only names and api_roots are exposed.

    Returns:
        ``{"ok": True, "profiles": [{"name", "api_root"}, ...]}`` or
        ``{"ok": False, "error": str}``.
    """
    try:
        return {"ok": True, "profiles": list_profile_summaries()}
    except ProfileError as exc:
        return {"ok": False, "error": str(exc)}


# ── MCP server builder ────────────────────────────────────────────────────────


def _build_server(FastMCP: type) -> Any:  # type: ignore[type-arg]
    """Wire resources and tools onto a fresh FastMCP instance.

    Receives the FastMCP class as an argument so the caller controls when
    the ``mcp`` library is imported and tests can wire it without starting
    a real stdio loop.
    """
    server = FastMCP(
        "pegasus-workflows",
        instructions=(
            "Use the resources to understand Pegasus workflow authoring rules "
            "and the tools to scaffold, validate, package, and dry-run-gate "
            "workflows without triggering any network writes."
        ),
    )

    @server.resource("pegasus://guide/authoring")
    def _res_guide_authoring() -> str:
        return resource_guide_authoring()

    @server.resource("pegasus://guide/input-contract")
    def _res_guide_input_contract() -> str:
        return resource_guide_input_contract()

    @server.resource("pegasus://guide/secrets-config")
    def _res_guide_secrets_config() -> str:
        return resource_guide_secrets_config()

    @server.resource("pegasus://reference/manifest")
    def _res_reference_manifest() -> str:
        return resource_reference_manifest()

    @server.resource("pegasus://reference/api")
    def _res_reference_api() -> str:
        return resource_reference_api()

    @server.resource("pegasus://reference/integration-config")
    def _res_reference_integration_config() -> str:
        return resource_reference_integration_config()

    @server.resource("pegasus://reference/floors")
    def _res_reference_floors() -> str:
        return resource_reference_floors()

    @server.resource("pegasus://reference/openapi")
    def _res_reference_openapi() -> str:
        return resource_reference_openapi()

    @server.tool()
    def scaffold_workflow(name: str, dest: str) -> dict:  # type: ignore[type-arg]
        """Scaffold a new workflow project at dest/name (wraps pegasus-workflows init)."""
        return tool_scaffold_workflow(name, dest)

    @server.tool()
    def validate_manifest(path_or_toml: str) -> dict:  # type: ignore[type-arg]
        """Validate a manifest file path or raw TOML text."""
        return tool_validate_manifest(path_or_toml)

    @server.tool()
    def diagram_prompt(project_dir: str, workflow: str | None = None) -> dict:  # type: ignore[type-arg]
        """Build the BYO-agent prompt(s) for drawing each workflow.mmd (read-only, no network)."""
        return tool_diagram_prompt(project_dir, workflow)

    @server.tool()
    def package_project(project_dir: str) -> dict:  # type: ignore[type-arg]
        """Package every workflow in project_dir into dist/ (wraps pegasus-workflows package)."""
        return tool_package_project(project_dir)

    @server.tool()
    def validate_integration_config(
        integration_id: str,
        mapping: Any,
        rules: Any,
        corpus: Any,
        base_url: str,
        token: str,
        floor: str | None = None,
        inbound: Any | None = None,
    ) -> dict:  # type: ignore[type-arg]
        """Dry-run the integration config publish gate (incl. floor + inbound). No write."""
        return tool_validate_integration_config(
            integration_id, mapping, rules, corpus, base_url, token, floor, inbound
        )

    @server.tool()
    def list_deployments(project_dir: str) -> dict:  # type: ignore[type-arg]
        """Read a project's deployments.toml ledger (read-only — no network)."""
        return tool_list_deployments(project_dir)

    @server.tool()
    def list_profiles() -> dict:  # type: ignore[type-arg]
        """List credential profile names + api_root — never a key (read-only)."""
        return tool_list_profiles()

    return server


# ── Typer command ─────────────────────────────────────────────────────────────


def mcp_command() -> None:
    """Start a stdio MCP server for AI coding agents.

    Exposes SDK resources and safe tools so any MCP-compatible agent can
    scaffold, validate, and package Pegasus workflows without network side
    effects.  Network-mutating operations (push, publish, run) are not exposed
    and remain human-gated via the CLI.

    The MCP dependency ships in the base package — a plain
    ``pip install pegasus-workflows-sdk`` is enough.
    """
    try:
        from mcp.server.fastmcp import FastMCP
    except ImportError:
        typer.secho(_MISSING_EXTRA_MSG, fg=typer.colors.RED, err=True)
        raise typer.Exit(code=1) from None

    server = _build_server(FastMCP)
    server.run("stdio")

def _public_base_url() -> str:
    """Base URL for the public discovery endpoints (env override, else prod)."""
    import os

    return (os.environ.get("PEGASUS_BASE_URL") or _DEFAULT_API_ROOT).rstrip("/")


def _fetch_public(path: str) -> str | None:
    """GET a PUBLIC (no-auth) discovery endpoint; None if unreachable."""
    try:
        import httpx

        with httpx.Client(timeout=10.0) as client:
            response = client.get(f"{_public_base_url()}{path}")
            response.raise_for_status()
            return response.text
    except Exception:
        return None



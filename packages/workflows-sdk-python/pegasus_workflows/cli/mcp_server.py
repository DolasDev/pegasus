def resource_reference_api() -> str:
    """PegasusClient method surface, generated by introspection at serve time."""
    lines = [
        "# Pegasus API Reference (PegasusClient)",
        "",
        "Generated by introspecting ``pegasus_workflows.api.PegasusClient`` at serve",
        "time — adding or renaming a method or changing its docstring updates this",
        "resource automatically.",
        "",
    ]
    for name, method in inspect.getmembers(PegasusClient, predicate=inspect.isfunction):
        if name.startswith("_"):
            continue
        try:
            sig = inspect.signature(method)
            sig_str = f"{name}{sig}"
        except (ValueError, TypeError):
            sig_str = name
        doc = inspect.getdoc(method) or ""
        lines.append(f"## {sig_str}")
        if doc:
            lines.append("")
            lines.append(doc)
        lines.append("")
    return "\n".join(lines)



def resource_guide_authoring() -> str:
    """Authoring guide: import surface, determinism rule, and input contract pointer."""
    return """\
# Pegasus Workflow Authoring Guide

## Import surface

Import Temporal primitives and the decorator from ``pegasus_workflows``:

    from pegasus_workflows import activity, pegasus_workflow, workflow
    from pegasus_workflows.api import PegasusClient   # activities only — never in workflow code

Decorate your workflow class:

    @pegasus_workflow(name="demo", version="0.1.0")
    class HelloWorkflow:
        @workflow.run
        async def run(self, arg: dict | str) -> str:
            ...

The ``name`` in ``@pegasus_workflow`` **must match** the manifest ``name`` field
exactly — do not use the Python class name.

## Determinism rule

Workflow code runs inside the Temporal determinism sandbox. It MUST NOT:
- perform any I/O (file, network, subprocess, environment reads)
- import ``httpx``, ``requests``, or any I/O library
- use ``random``, ``datetime.now()``, or any non-deterministic call

All I/O belongs in ``@activity.defn`` functions, which run outside the sandbox.
Use ``PegasusClient`` only inside activities, never inside workflow methods.

## Activities

Build the client with ``PegasusClient.from_runtime()`` — it reads the two env
vars the tenant runner injects (``PEGASUS_API_BASE_URL`` /
``PEGASUS_RUNTIME_TOKEN``), so you never hardcode a base URL or token. A future
rename of those vars is then a one-line SDK fix, not a per-workflow break, and a
run outside the runner fails with a clear named error instead of a bare
``KeyError``.

    from pegasus_workflows import activity
    from pegasus_workflows.api import PegasusClient

    @activity.defn
    async def fetch_quote(quote_id: str) -> dict:
        client = PegasusClient.from_runtime()
        return client.get_workflow(quote_id)  # example — use the right method

## Input contract

See ``pegasus://guide/input-contract`` for the three argument shapes your
``run()`` method must handle (trigger-fired, manual run, CLI test).

## Secrets & configuration

To read per-tenant secrets or config at runtime, declare ``ReadWorkflowSecret``
/ ``ReadWorkflowConfig`` in your manifest ``required_actions`` and call
``client.get_secret(...)`` / ``client.get_config(...)`` inside an activity. See
``pegasus://guide/secrets-config`` for publishing and usage.

## Workflow diagram (required to publish)

Every workflow must ship a Mermaid diagram at ``<source_dir>/workflow.mmd``. The
tenant UI renders it so business users can confirm the workflow matches their
rules, and ``package`` / ``push`` fail without it. There is no AI service that
draws it for you — **you, the coding agent, draw it.** Call the ``diagram_prompt``
tool to get each workflow's source plus the exact output path and formatting
rules, produce a Mermaid ``flowchart TD`` that faithfully reflects the control
flow (no invented steps), and write it to the path the tool names.
``scaffold_workflow`` seeds a starter ``workflow.mmd`` so a fresh project already
publishes; refine it before publishing for real.
"""


def resource_guide_input_contract() -> str:
    """The three input shapes + a worked resolver example."""
    return """\
# Pegasus Workflow Input Contract

Your ``run()`` method receives a single positional argument. Its shape depends
on how the workflow was started:

## Shape 1 — Trigger-fired (domain-event trigger)

The dispatcher injects the full event envelope:

    {
        "domainEventId": "<uuid>",
        "eventType": "quote.accepted",
        "occurredAt": "<ISO-8601>",
        "payload": {"quoteId": "<id>", "moveId": "<id>"}
    }

Read ids from ``arg["payload"]["quoteId"]`` etc. The payload is a pointer,
not a snapshot — always re-fetch authoritative state from the Pegasus API.

## Shape 2 — Manual run

``POST /api/v1/workflows/:id/run`` passes:

    {"executionId": "<uuid>", "input": <user-supplied dict>}

Read your business data from ``arg["input"]``.

## Shape 3 — CLI test

``pegasus-workflows test <name>`` passes a raw string for local-dev parity.

## Shape 4 — Scheduled (cron trigger)

A SCHEDULE trigger (``pegasus-workflows schedule create``) fires on its cron
cadence, passing a tick envelope in the run input:

    {"executionId": "<uuid>",
     "input": {"scheduledAt": "<ISO-8601>", "schedule": "<cron>", "triggerId": "<id>"}}

Read it from ``arg["input"]``; detect a scheduled tick by the ``scheduledAt``
key. A tick carries no entity — the workflow does its own work (e.g. advance a
cursor and poll). It is distinct from a manual run, whose ``input`` is your own
business data.

## Recommended pattern: a module-level resolver (unit-testable)

Write a plain function — not a method — so it stays testable without a Temporal
worker context:

    def _resolve_quote_id(arg: dict | str) -> str:
        if isinstance(arg, str):
            return arg
        payload = arg.get("payload") if isinstance(arg, dict) else None
        if isinstance(payload, dict) and payload.get("quoteId"):
            return str(payload["quoteId"])
        inp = arg.get("input") if isinstance(arg, dict) else None
        if isinstance(inp, dict) and inp.get("scheduledAt"):
            return "scheduled-tick"        # Shape 4: a cron firing, no entity
        if isinstance(inp, dict) and inp.get("quote_id"):
            return str(inp["quote_id"])
        return "quote-unknown"
"""


def resource_guide_secrets_config() -> str:
    """How to publish and use per-tenant workflow secrets & configuration."""
    return """\
# Pegasus Workflow Secrets & Configuration

A workflow reads two kinds of per-tenant key/value data at runtime:

- **Secrets** — write-once, encrypted at rest, the plaintext is only ever handed
  to the workflow runtime (e.g. a third-party API key). Read action:
  ``ReadWorkflowSecret``.
- **Config** — plain, editable values (e.g. a region, a feature flag, a base URL).
  Read action: ``ReadWorkflowConfig``.

Both are scoped to the whole tenant: every workflow the tenant owns reads the
same namespace. A secret and a config entry may share a key — they are separate
namespaces.

## Organize with groups (recommended)

Every secret/config belongs to a **group** — a logical namespace for keeping
related keys together (e.g. ``billing``, ``notifications``, ``crm``). An entry
created without a group lands in ``global``.

**Best practice: put every key in a meaningful group; reserve ``global`` for
truly cross-cutting values.** Groups keep a growing store navigable and let you
list one area at a time. The group is part of an entry's identity, so the same
key may exist in different groups (e.g. ``API_KEY`` in both ``billing`` and
``crm``) — reads/writes must name the group (default ``global``). Groups are
organizational only; they are not an access-control boundary.

    pegasus-workflows secrets set STRIPE_API_KEY "sk_live_..." --group billing --token vnd_...
    pegasus-workflows secrets list --group billing --token vnd_...   # one group
    pegasus-workflows secrets list --token vnd_...                   # every group

    client.set_config("DEFAULT_REGION", "us-east-1", group="billing")
    region = client.get_config("DEFAULT_REGION", group="billing")

## 1. Declare what your workflow needs (manifest)

Add the read actions to ``required_actions`` in ``pegasus-workflows.toml`` so the
runtime service account is authorized to read them:

    [[workflow]]
    name = "send_quote_followup"
    version = "0.1.0"
    entry_points = ["send_quote_followup.workflow:SendQuoteFollowup"]
    required_actions = ["ReadQuote", "ReadWorkflowSecret", "ReadWorkflowConfig"]

## 2. Publish values (one-time, by a developer/admin)

Values are NOT part of the workflow artifact — publish them out of band with a
token holding ``ManageWorkflowSecrets`` / ``ManageWorkflowConfigs`` (the
``workflow_developer`` or ``tenant_admin`` role), via the CLI:

    pegasus-workflows secrets set STRIPE_API_KEY "sk_live_..." --token vnd_... --base-url https://api...
    pegasus-workflows config  set DEFAULT_REGION us-east-1   --token vnd_... --base-url https://api...
    pegasus-workflows secrets list --token vnd_...      # metadata only, never values
    pegasus-workflows config  list --token vnd_...

or from Python:

    client = PegasusClient(base_url="https://...", token="vnd_...")
    client.set_secret("STRIPE_API_KEY", "sk_live_...")
    client.set_config("DEFAULT_REGION", "us-east-1")

Secrets are **write-once** — to rotate, ``delete_secret`` then ``set_secret``
again. Config is an idempotent upsert (``set_config`` replaces the value).

## 3. Read values at runtime (inside an activity)

Read them with the runtime ``vnd_`` token inside an ``@activity.defn`` function —
never in workflow code (httpx is sandboxed there):

    from pegasus_workflows import activity
    from pegasus_workflows.api import PegasusClient

    @activity.defn
    async def charge_customer(amount_cents: int) -> str:
        client = PegasusClient.from_runtime()                       # runner's env contract
        api_key = client.get_secret("STRIPE_API_KEY", group="billing")  # needs ReadWorkflowSecret
        region = client.get_config("DEFAULT_REGION")                # group defaults to "global"
        ...

``get_secret`` / ``get_config`` take an optional ``group=`` (default ``"global"``)
and raise ``PegasusApiError`` with status 404 if the key is unset **in that group**
and 403 if the manifest did not declare the matching read action.
"""



#!/usr/bin/env bash
# =============================================================================
# env-from-ssm.sh — write apps/mobile/.env from the deployed environment's SSM
#                   parameters. The ONE source of truth for the mobile runtime
#                   config: release builds (.github/actions/mobile-eas-config)
#                   and local dev (npm run env:prod) both call this script, so a
#                   developer's .env can't drift from what ships.
#
# Usage: scripts/env-from-ssm.sh [<output-path>]
#          <output-path>  defaults to apps/mobile/.env (resolved from this
#                         script's location, not the caller's cwd)
#
# AWS credentials come from the environment: the OIDC role in CI, or a profile
# locally (npm run env:prod sets AWS_PROFILE=dolas-pegasus-prod-ro). Which
# account the credentials belong to decides which API/user pool the app uses.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${1:-$SCRIPT_DIR/../.env}"
export AWS_REGION="${AWS_REGION:-us-east-1}"

param() { aws ssm get-parameter --name "$1" --query Parameter.Value --output text; }

USER_POOL_ID=$(param /pegasus/admin/cognito-user-pool-id)
CLIENT_ID=$(param /pegasus/mobile/cognito-client-id)
HOSTED_UI=$(param /pegasus/admin/cognito-hosted-ui-domain)
API_DOMAIN=$(param /dolas/pegasus/api/domain-name)

# User pool + client IDs aren't strict secrets (they ship inside any built app)
# but masking keeps the job log tidy.
if [[ -n "${GITHUB_ACTIONS:-}" ]]; then
  echo "::add-mask::$USER_POOL_ID"
  echo "::add-mask::$CLIENT_ID"
fi

cat > "$OUT" <<ENVEOF
# Generated by apps/mobile/scripts/env-from-ssm.sh — do not commit
EXPO_PUBLIC_API_URL=https://${API_DOMAIN}
EXPO_PUBLIC_COGNITO_REGION=us-east-1
EXPO_PUBLIC_COGNITO_USER_POOL_ID=${USER_POOL_ID}
EXPO_PUBLIC_COGNITO_CLIENT_ID=${CLIENT_ID}
EXPO_PUBLIC_COGNITO_DOMAIN=${HOSTED_UI}
EXPO_PUBLIC_COGNITO_REDIRECT_URI=movingapp://auth/callback
ENVEOF

echo "Wrote $OUT:"
grep -E '^EXPO_PUBLIC_(API_URL|COGNITO_REGION|COGNITO_REDIRECT_URI)=' "$OUT"
